"""Turn saved Brittain Code conversations into trajectory training examples.

    python3 harvest_chats.py --in <chats dir> --spec <driver spec html>
    python3 harvest_chats.py --in ... --spec ... --stats

ONE EXAMPLE PER ASSISTANT TURN, NOT PER CONVERSATION
The agent loop calls the model once per step and rebuilds the message array
each time, so a step -- not a conversation -- is the unit the model actually
has to produce. A 50-step turn is 50 training examples with growing context,
which is also how the model will meet it at serving time.

WHAT GETS DROPPED, AND WHY
  dead mode        'jarvis' and its rename 'brittain' were a dev-only voice
                   mode that never shipped. They call app_status, which is in
                   no released tool array, and their successor in 1.5.0 has a
                   prompt and tool slice we do not have yet.
  weak source      trajectories generated by 124M-class models are mistakes to
                   imitate, not behaviour to learn.
  removed tool     eleven tools were folded away in one consolidation commit.
                   A target calling one teaches the model to emit a call the
                   dispatcher rejects with "Error: Tool unavailable".
                   NOTE these are dropped as TARGETS only. The same call
                   appearing earlier in the context is history and stays --
                   the model needs to see what a real conversation looks like,
                   including the parts that predate a refactor.
  empty target     no content and no tool calls is the loop's stall path, not
                   an output worth reproducing.

WHAT IS DELIBERATELY KEPT
  MCP calls        playwright and openosint are not part of the 55 and were
                   never meant to be baked. They stay because a driver that can
                   only call baked tools is useless the moment a server is
                   added; these teach "call the tools you were handed".
  Error: results   13% of tool results in this corpus carry the prefix. The
                   failure surfaces are prescribed behaviour, and they cannot
                   be synthesised convincingly.
  thinking         kept as its own field. The app toggles thinking per request,
                   so both modes have to work and the trace must be separable.
"""
import argparse
import collections
import json
import os
import re
import sys

REMOVED_TOOLS = {
    "analyze_file_structure", "calculate_file_hash", "count_lines", "file_info",
    "find_files", "find_largest_files", "get_file_type", "list_directory",
    "pattern_search_deep", "replace_in_file", "search_in_file",
}
DEAD_MODES = {"jarvis", "brittain"}
# Substrings, because the same family appears under several tags.
WEAK_SOURCES = ("brittain1", "124m", "laguna-xs", "xs_bs", "xs-2.1")

# Display-only keys, stripped at the inference boundary by modelReadyMessages().
DISPLAY_ONLY = {
    "displayContent", "attachments", "imageTypes", "pinned", "excludedFromInference",
    "compactionRecord", "meta", "pendingRunId", "clientRunId",
}
RESULT_CAP = 32_000            # boundToolResult(): 60% head, 40% tail
ERROR_RE = re.compile(r"\s*(\[MCP auto-approved\]\s*)?(MCP tool error:|Error:)", re.I)


def bound_result(text):
    """Reproduce boundToolResult so training data matches what the model sees."""
    if not isinstance(text, str) or len(text) <= RESULT_CAP:
        return text
    head = int(RESULT_CAP * 0.6)
    tail = RESULT_CAP - head
    omitted = len(text) - RESULT_CAP
    notice = ("\n[result shortened: approximately %d characters omitted. Use a "
              "narrower query, a page snapshot, or a targeted search.]\n" % omitted)
    return text[:head] + notice + text[-tail:]


def clean_message(m):
    """Strip display-only keys and bound oversized results."""
    out = {k: v for k, v in m.items() if k not in DISPLAY_ONLY}
    if out.get("role") == "tool":
        out["content"] = bound_result(out.get("content"))
    return out


def call_names(msg):
    return [(c.get("function") or {}).get("name") for c in (msg.get("tool_calls") or [])]


def load_live_tools(spec_path):
    html = open(spec_path, encoding="utf-8").read()
    names = set(re.findall(r'<details class="tool" data-name="([^"]+)"', html))
    if not names:
        raise SystemExit("no tool names found in %s" % spec_path)
    return names


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--in", dest="src", required=True)
    ap.add_argument("--spec", required=True, help="driver spec html, for the live tool list")
    ap.add_argument("--out", default="trajectories.jsonl")
    ap.add_argument("--stats", action="store_true", help="report only, write nothing")
    ap.add_argument("--keep-weak", action="store_true",
                    help="keep trajectories from tiny source models")
    args = ap.parse_args()

    live = load_live_tools(args.spec)
    dropped = collections.Counter()
    kept_by_mode = collections.Counter()
    tools_seen = collections.Counter()
    ctx_lens = []
    n_chats = n_examples = n_with_calls = n_errors = 0

    out = None if args.stats else open(args.out, "w", encoding="utf-8")

    # Recursive: the export arrives zipped with the files under a chats/ dir,
    # and a flat listdir silently finds nothing and reports success.
    paths = sorted(
        os.path.join(root, f)
        for root, _, files in os.walk(args.src)
        for f in files
        if f.endswith(".json") and f != "index.json"
    )
    if not paths:
        raise SystemExit("no chat files under %s" % args.src)
    for fpath in paths:
        try:
            data = json.load(open(fpath, encoding="utf-8"))
        except ValueError:
            dropped["unparseable chat"] += 1
            continue

        conv = data.get("conversation") or []
        if not conv:
            dropped["empty conversation"] += 1
            continue

        mode = data.get("mode") or "code"   # the field postdates the oldest chats
        if mode in DEAD_MODES:
            dropped["dead mode (jarvis/brittain)"] += 1
            continue
        model = (data.get("model") or "?").lower()
        if not args.keep_weak and any(w in model for w in WEAK_SOURCES):
            dropped["weak source model"] += 1
            continue

        n_chats += 1
        kept_by_mode[mode] += 1
        history = []
        for msg in conv:
            role = msg.get("role")
            if role == "assistant":
                names = call_names(msg)
                has_content = bool((msg.get("content") or "").strip())
                if not names and not has_content:
                    dropped["empty assistant turn"] += 1
                    history.append(clean_message(msg))
                    continue
                bad = [n for n in names if n in REMOVED_TOOLS]
                if bad:
                    dropped["target calls removed tool"] += 1
                    history.append(clean_message(msg))   # still real history
                    continue

                n_examples += 1
                if names:
                    n_with_calls += 1
                tools_seen.update(names)
                ctx_lens.append(len(history))
                if out:
                    out.write(json.dumps({
                        "chat_id": data.get("id"),
                        "mode": mode,
                        # What the app REQUESTED, which is not what happened:
                        # over the API some models reason regardless, and three
                        # chats marked think=false carry traces (one has 129).
                        "think_requested": bool(data.get("think")),
                        # What this turn actually produced. This is the field to
                        # train and slice on.
                        "has_trace": bool((msg.get("thinking") or "").strip()),
                        "source_model": data.get("model"),
                        "cwd_present": bool(data.get("cwd")),
                        "context": history[:],           # copy: history keeps growing
                        "target": {
                            "content": msg.get("content") or "",
                            "thinking": msg.get("thinking") or "",
                            "tool_calls": msg.get("tool_calls") or [],
                        },
                        "unbaked_tools": sorted({n for n in names if n not in live}),
                    }) + "\n")
            elif role == "tool":
                c = msg.get("content") or ""
                if isinstance(c, str) and ERROR_RE.match(c):
                    n_errors += 1
            history.append(clean_message(msg))

    if out:
        out.close()

    print("chats kept        : %d" % n_chats)
    print("examples written  : %d  (%d call a tool, %d are text-only)"
          % (n_examples, n_with_calls, n_examples - n_with_calls))
    print("error results seen: %d" % n_errors)
    if ctx_lens:
        ctx_lens.sort()
        print("context messages  : median %d, p90 %d, max %d"
              % (ctx_lens[len(ctx_lens) // 2], ctx_lens[int(len(ctx_lens) * 0.9)], ctx_lens[-1]))
    print("by mode           : %s" % dict(kept_by_mode))
    print("\ndropped:")
    for why, n in dropped.most_common():
        print("  %-28s %d" % (why, n))

    unbaked = {t: n for t, n in tools_seen.items() if t not in live}
    print("\ncalls to tools outside the 55: %d across %d names"
          % (sum(unbaked.values()), len(unbaked)))
    uncovered = sorted(live - set(tools_seen))
    print("live tools with no coverage  : %d of %d" % (len(uncovered), len(live)))
    print("   " + ", ".join(uncovered))
    if not args.stats:
        print("\nwrote %s" % args.out)


if __name__ == "__main__":
    main()
